function assert(condition: boolean, message: string): void {
  if (!condition) throw new Error(message);
}

class HttpResult {
  readonly status: number;
  readonly headers: Headers;
  readonly raw: string;
  readonly json: Record<string, unknown> | null;

  constructor(status: number, headers: Headers, raw: string) {
    this.status = status;
    this.headers = headers;
    this.raw = raw;
    let parsed: unknown = null;
    try {
      parsed = raw.length > 0 ? JSON.parse(raw) : null;
    } catch {
      parsed = null;
    }
    this.json = parsed && typeof parsed === "object" ? (parsed as Record<string, unknown>) : null;
  }

  get fieldErrors(): Record<string, string> {
    const errors = (this.json?.errors ?? {}) as Record<string, string>;
    return errors && typeof errors === "object" ? errors : {};
  }

  get messageText(): string {
    return typeof this.json?.message === "string" ? this.json.message : "";
  }
}

async function call(
  path: string,
  init: { method: string; body?: FormData | string | Uint8Array | null; headers?: Record<string, string> },
): Promise<HttpResult> {
  const res = await fetch(BASE + path, { ...init, redirect: "manual" });
  const raw = await res.text();
  return new HttpResult(res.status, res.headers, raw);
}

const jsonPost = (path: string, body: unknown) =>
  call(path, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify(body),
  });

