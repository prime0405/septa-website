/** Text fields only — the file part is added by the caller. */
function appendCareerFields(fd: FormData, payload: Record<string, unknown>): void {
  for (const [key, value] of Object.entries(payload)) {
    if (value === undefined || value === null) continue;
    fd.append(key, typeof value === "string" ? value : String(value));
  }
}

function fakePdf(size = 2048): Uint8Array {
  const header = "%PDF-1.4\n% smoke test file generated by scripts/smoke.ts\n";
  const bytes = new Uint8Array(size);
  bytes.set(new TextEncoder().encode(header), 0);
  bytes.set(new TextEncoder().encode("\n%%EOF\n"), Math.max(0, size - 7));
  return bytes;
}

function readStoredCount(stream?: "contact" | "requests" | "applications"): number {
  // Reads the same file the API writes to. Safe with a live server: readers only here.
  if (!existsSync(config.dbPath)) return -1;
  return listInbox(stream, 500).length;
}

