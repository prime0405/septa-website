interface Row {
  group: string;
  name: string;
  status: "PASS" | "FAIL";
  detail: string;
}

async function main(): Promise<number> {
  const rows: Row[] = [];
  let notes: string[] = [];

  console.log(`\nSepta API smoke — ${BASE}`);
  let reachable = false;
  try {
    const probe = await fetch(`${BASE}/api/status`, { signal: AbortSignal.timeout(5000) });
    reachable = probe.ok;
    await probe.body?.cancel();
  } catch {
    reachable = false;
  }
  if (!reachable) {
    console.error(
      `\nThe API at ${BASE} is not answering GET /api/status.\nStart it first:  npm run start:api   (or npm run dev)\n`,
    );
    return 1;
  }

  for (const current of cases) {
    notes = [];
    try {
      await current.run((note) => notes.push(note));
      rows.push({ group: current.group, name: current.name, status: "PASS", detail: notes.join(" · ") });
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      rows.push({
        group: current.group,
        name: current.name,
        status: "FAIL",
        detail: [message, ...notes].filter((part) => part.length > 0).join(" · "),
      });
    }
  }

  const groupWidth = Math.max(...rows.map((row) => row.group.length), 6);
  const nameWidth = Math.min(72, Math.max(...rows.map((row) => row.name.length), 20));
  const failed = rows.filter((row) => row.status === "FAIL");

  console.log("");
  console.log(`${"GROUP".padEnd(groupWidth)}  RESULT  CASE`);
  for (const row of rows) {
    console.log(
      `${row.group.padEnd(groupWidth)}  ${row.status}  ${row.name.slice(0, nameWidth).padEnd(nameWidth)}`,
      row.detail.length > 0 ? `— ${row.detail}` : "",
    );
  }
  console.log("");
  console.log(`${rows.length - failed.length}/${rows.length} checks passed.`);
  if (failed.length > 0) {
    console.log(`Failed: ${failed.map((row) => `${row.group}/${row.name}`).join(" | ")}`);
    return 1;
  }
  console.log("All checks passed. Note: this run says nothing about real SMTP delivery — see README.");
  return 0;
}

main()
  .then((code) => process.exit(code))
  .catch((error: unknown) => {
    console.error("Smoke run crashed:", error);
    process.exit(1);
  });
