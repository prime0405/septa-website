/**
 * Submissions share one fixed window per endpoint, so the later cases in a group can be
 * rate limited by the earlier ones. When that happens, wait out the advertised window
 * and try again rather than reporting a false failure.
 */
async function callAwaitingWindow(
  path: string,
  body: FormData,
  attempts = 3,
): Promise<HttpResult> {
  let res = await call(path, { method: "POST", body });
  for (let i = 1; i < attempts && res.status === 429; i += 1) {
    const waitSeconds = Number.parseInt(res.headers.get("retry-after") ?? "60", 10) + 2;
    console.log(`    (rate limited — waiting ${waitSeconds}s before retrying)`);
    await new Promise((resolve) => setTimeout(resolve, waitSeconds * 1000));
    res = await call(path, { method: "POST", body });
  }
  return res;
}

